"use strict";

/**
 * ISA harness driver.
 *
 * For every case in cases.js this script:
 *   1. translates the program with the real tools/ppcx translator,
 *   2. generates one C harness that runs all programs and prints the final
 *      CPU and memory state,
 *   3. compiles the harness with a real host compiler,
 *   4. runs it and compares the output with tests/isa/oracle.js.
 *
 * The comparison is exact and covers all 32 GPRs, XER, CR, LR, CTR and the
 * memory windows the cases declare. `node tests/isa/run.js` exits non-zero on
 * any mismatch and prints the differing lines.
 *
 * Compiler discovery: PPCX_CC, then cc/gcc/clang/tcc on PATH, then the usual
 * TCC install locations on Windows. When none is found the driver returns
 * `compiler: null` and callers decide whether that is a skip or a failure
 * (CI installs a compiler, so it always runs there).
 */

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { execFileSync, spawnSync } = require("node:child_process");

const { translateFunction } = require("../../tools/ppcx/lib/translate.js");
const { buildCases } = require("./cases.js");
const oracle = require("./oracle.js");

const REPO_ROOT = path.resolve(__dirname, "..", "..");
const RUNTIME_INCLUDE = path.join(REPO_ROOT, "src", "runtime", "include");

const PROG_BASE = 0x00010000;
const PROG_STRIDE = 0x100;

function findCompiler() {
    const candidates = [];
    if (process.env.PPCX_CC) candidates.push(process.env.PPCX_CC);
    candidates.push("cc", "gcc", "clang", "tcc");
    if (process.platform === "win32") {
        candidates.push(
            path.join(os.homedir(), "Tools", "analysis", "tcc", "tcc", "tcc.exe"),
            "C:\\tcc\\tcc.exe"
        );
    }
    for (const c of candidates) {
        for (const flag of ["--version", "-v"]) {
            const r = spawnSync(c, [flag], { encoding: "utf8" });
            if (r.status === 0 || (r.stdout && r.stdout.length) || (r.stderr && r.stderr.length)) {
                if (!r.error) return c;
            }
        }
    }
    return null;
}

/* ------------------------------------------------------------------ */
/* C generation                                                        */
/* ------------------------------------------------------------------ */

function translateCase(caseDef, index) {
    const base = PROG_BASE + index * PROG_STRIDE;
    const data = Buffer.alloc(caseDef.prog.length * 4);
    caseDef.prog.forEach((w, i) => data.writeUInt32BE(w >>> 0, i * 4));
    const end = base + data.length;
    const res = translateFunction({
        data,
        base,
        start: base,
        end,
        textBase: base,
        textEnd: end,
        startSet: [base],
        emitSet: [base],
    });
    return { base, name: res.name, code: res.code };
}

function cHex(n) {
    return `0x${(n >>> 0).toString(16).padStart(8, "0")}u`;
}

function buildHarness(cases) {
    const out = [];
    out.push("/* Generated by tests/isa/run.js: do not edit. */");
    out.push('#include "ppcx_abi.h"');
    out.push("#include <stdio.h>");
    out.push("#include <stdlib.h>");
    out.push("#include <string.h>");
    out.push("");
    out.push(`#define PPCX_ARENA ${oracle.ARENA}u`);
    out.push("u8 *ppcx_memory = NULL;");
    out.push("static Cpu cpu;");
    out.push("");
    out.push("void ppcx_hle_call(Cpu *c, u32 idx) { (void)c; (void)idx; }");
    out.push("void ppcx_dispatch(Cpu *c, u32 target) { (void)c; (void)target; }");
    out.push("void ppcx_call_unknown(Cpu *c, u32 target) { (void)c; (void)target; }");
    out.push("void ppcx_unimpl(Cpu *c, u32 addr) { (void)c; (void)addr; }");
    out.push("void ppcx_trap(Cpu *c, u32 addr, const char *name) { (void)c; (void)addr; (void)name; }");
    out.push("void ppcx_trace_enter(u32 addr) { (void)addr; }");
    out.push("u32 ppcx_import_addr(u32 idx) { return 0x0f000000u + idx; }");
    out.push("");

    for (let i = 0; i < cases.length; i++) {
        const t = translateCase(cases[i], i);
        out.push(`/* case ${i}: ${cases[i].name} */`);
        out.push(t.code);
        out.push("");
    }

    out.push("static void print_mem(u32 addr, u32 len) {");
    out.push('    printf("mem %08x ", addr);');
    out.push("    for (u32 i = 0; i < len; i++) printf(\"%02x\", ppcx_memory[addr + i]);");
    out.push('    printf("\\n");');
    out.push("}");
    out.push("");
    out.push("/* Single-precision print of an FPR lane: NaN prints canonically so the");
    out.push(" * value-level model never compares NaN payloads. */");
    out.push("static u32 print_single(u64 x) {");
    out.push("    if (((x >> 52) & 0x7ffu) == 0x7ffu && (x & 0x000fffffffffffffull) != 0ull) return 0x7fc00000u;");
    out.push("    return ppcx_single_bits_from_bits(x);");
    out.push("}");
    out.push("");
    out.push("static void report(Cpu *c, const u32 *dumps, u32 dumpCount) {");
    out.push('    printf("gpr");');
    out.push('    for (int i = 0; i < 32; i++) printf(" %08x", c->gpr[i]);');
    out.push('    printf("\\n");');
    out.push('    printf("xer %08x cr %08x lr %08x ctr %08x\\n", c->xer, c->cr, c->lr, c->ctr);');
    out.push('    printf("fpr");');
    out.push('    for (int i = 0; i < 32; i++) printf(" %08x %08x", print_single(c->fpr[i].ps0.u), print_single(c->fpr[i].ps1.u));');
    out.push('    printf("\\n");');
    out.push('    printf("gqr");');
    out.push('    for (int i = 0; i < 8; i++) printf(" %08x", c->gqr[i]);');
    out.push('    printf(" hid2 %08x\\n", c->hid2);');
    out.push("    for (u32 i = 0; i < dumpCount; i++) print_mem(dumps[2 * i], dumps[2 * i + 1]);");
    out.push("}");
    out.push("");

    for (let i = 0; i < cases.length; i++) {
        const c = cases[i];
        const init = c.init || {};
        const fn = translateCase(c, i).name;
        out.push(`static void case_${i}(void) {`);
        out.push("    memset(&cpu, 0, sizeof cpu);");
        out.push("    cpu.resv = 0xffffffffu;");
        out.push("    cpu.hid2 = PPCX_HID2_LSQE; /* modelled boot state */");
        for (const [k, v] of Object.entries(init.gpr || {})) out.push(`    cpu.gpr[${k}] = ${cHex(v)};`);
        if (init.xer !== undefined) out.push(`    cpu.xer = ${cHex(init.xer)};`);
        if (init.cr !== undefined) out.push(`    cpu.cr = ${cHex(init.cr)};`);
        if (init.lr !== undefined) out.push(`    cpu.lr = ${cHex(init.lr)};`);
        if (init.ctr !== undefined) out.push(`    cpu.ctr = ${cHex(init.ctr)};`);
        if (init.hid2 !== undefined) out.push(`    cpu.hid2 = ${cHex(init.hid2)};`);
        for (const [k, v] of Object.entries(init.gqr || {})) out.push(`    cpu.gqr[${k}] = ${cHex(v)};`);
        for (const [k, v] of Object.entries(init.fpr || {}))
            for (let lane = 0; lane < 2; lane++)
                out.push(`    cpu.fpr[${k}].ps${lane}.d = (double)ppcx_bits_f32(${cHex(v[lane])});`);
        out.push("    memset(ppcx_memory, 0, PPCX_ARENA);");
        for (const m of c.mem || []) {
            const list = Buffer.from(m.hex, "hex");
            const items = Array.from(list).map((b) => `0x${b.toString(16).padStart(2, "0")}`);
            out.push(`    { static const unsigned char d[] = {${items.join(",")}};`);
            out.push(`      memcpy(ppcx_memory + ${cHex(m.addr)}, d, sizeof d); }`);
        }
        const dumps = c.dump || [];
        if (dumps.length) {
            const flat = dumps.flatMap((d) => [cHex(d.addr), `${d.len}u`]);
            out.push(`    { static const u32 dumps[] = {${flat.join(", ")}};`);
            out.push(`      ${fn}(&cpu);`);
            out.push("      report(&cpu, dumps, sizeof dumps / sizeof dumps[0] / 2); }");
        } else {
            out.push(`    ${fn}(&cpu);`);
            out.push("    report(&cpu, NULL, 0);");
        }
        out.push("}");
        out.push("");
    }

    out.push("int main(void) {");
    out.push("    ppcx_memory = (u8 *)calloc(1, PPCX_ARENA);");
    out.push("    if (!ppcx_memory) return 2;");
    for (let i = 0; i < cases.length; i++) out.push(`    case_${i}();`);
    out.push("    free(ppcx_memory);");
    out.push("    return 0;");
    out.push("}");
    out.push("");
    return out.join("\n");
}

/* ------------------------------------------------------------------ */
/* Runner                                                              */
/* ------------------------------------------------------------------ */

function compileAndRun(source, compiler, workDir) {
    const srcPath = path.join(workDir, "isa_harness.c");
    const exePath = path.join(workDir, process.platform === "win32" ? "isa_harness.exe" : "isa_harness");
    fs.writeFileSync(srcPath, source);

    const args = [];
    if (!/(^|[\\/])tcc(\.exe)?$/i.test(compiler)) args.push("-std=c11", "-O0", "-Wall");
    args.push("-I", RUNTIME_INCLUDE, "-o", exePath, srcPath, "-lm");
    let r = spawnSync(compiler, args, { encoding: "utf8" });
    if (r.status !== 0) {
        // Some toolchains (TCC on Windows) link without a separate libm.
        const retry = args.filter((a) => a !== "-lm");
        r = spawnSync(compiler, retry, { encoding: "utf8" });
        if (r.status !== 0) {
            throw new Error(
                `compiling the ISA harness failed\ncommand: ${compiler} ${retry.join(" ")}\n` +
                    `stdout:\n${r.stdout}\nstderr:\n${r.stderr}`
            );
        }
    }
    const run = spawnSync(exePath, [], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    if (run.status !== 0) throw new Error(`the ISA harness exited with ${run.status}\n${run.stderr}`);
    return run.stdout;
}

function runHarness(opts = {}) {
    const cases = buildCases();
    const compiler = opts.compiler !== undefined ? opts.compiler : findCompiler();
    if (!compiler) return { compiler: null, cases: cases.length, failures: [], skipped: true };

    const workDir = opts.workDir || fs.mkdtempSync(path.join(os.tmpdir(), "ppcx-isa-"));
    const source = buildHarness(cases);
    const output = compileAndRun(source, compiler, workDir);
    const blocks = output.split(/\r?\n/).filter((l) => l.length > 0);

    const failures = [];
    let cursor = 0;
    for (let i = 0; i < cases.length; i++) {
        const expected = oracle.evaluate(cases[i]);
        const actual = blocks.slice(cursor, cursor + expected.length);
        cursor += expected.length;
        if (expected.length !== actual.length || expected.some((l, k) => l !== actual[k])) {
            failures.push({
                id: i,
                name: cases[i].name,
                expected,
                actual,
            });
        }
    }
    if (cursor !== blocks.length) {
        failures.push({
            id: -1,
            name: "output length",
            expected: [`${cursor} state lines`],
            actual: [`${blocks.length} state lines`],
        });
    }
    return { compiler, cases: cases.length, failures, lines: blocks.length, workDir };
}

/* ------------------------------------------------------------------ */
/* CLI                                                                 */
/* ------------------------------------------------------------------ */

function main() {
    const res = runHarness();
    if (!res.compiler) {
        console.log("isa: skipped, no C compiler found (set PPCX_CC to one)");
        return 0;
    }
    console.log(`isa: ${res.cases} programs, compiled with ${res.compiler}, ${res.lines} state lines`);
    if (!res.failures.length) {
        console.log("isa: OK, generated code matches the independent oracle");
        return 0;
    }
    console.log(`isa: ${res.failures.length} MISMATCHES`);
    for (const f of res.failures.slice(0, 10)) {
        console.log(`\n--- case ${f.id}: ${f.name}`);
        for (let i = 0; i < Math.max(f.expected.length, f.actual.length); i++) {
            const e = f.expected[i] === undefined ? "<missing>" : f.expected[i];
            const a = f.actual[i] === undefined ? "<missing>" : f.actual[i];
            if (e !== a) {
                console.log(`  oracle:  ${e}`);
                console.log(`  emitted: ${a}`);
            }
        }
    }
    return 1;
}

if (require.main === module) process.exit(main());

module.exports = { runHarness, buildHarness, findCompiler, translateCase, PROG_BASE, PROG_STRIDE };
